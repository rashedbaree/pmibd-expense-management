/* eslint-disable @typescript-eslint/no-require-imports -- one-off CommonJS script, like the others in scripts/ */
// One-off utility: copies the Event check-in data (attendees + scan log) from
// the standalone check-in app's tables into the checkin_* tables created by
// migration 0016_event_checkin.sql.
//
//   source:  attendees, scan_log                (the standalone app's tables)
//   target:  checkin_attendees, checkin_scan_log (this app's tables)
//
// The source and target can be different Supabase projects (dev -> prod) or
// the same one (a dev rehearsal: copy attendees -> checkin_attendees inside
// DEV first, to try the new pages before touching prod).
//
// Safety:
//   * Dry run by default. Nothing is written without --apply.
//   * Refuses to write into a target that already has rows (a second run
//     would duplicate the scan log). Pass --allow-nonempty only if you know
//     why. To start over, truncate the checkin_* tables in the SQL Editor.
//   * --apply asks you to type the target project's ref (the bit before
//     .supabase.co) first, so pointing at PROD by mistake is hard.
//   * Attendee ids are preserved, so the scan log's links to attendees stay
//     valid. Scan-log ids are regenerated by the database (order is kept).
//
// Usage:
//   1. Run supabase/migrations/0016_event_checkin.sql on the TARGET project
//      (Supabase Dashboard -> SQL Editor).
//   2. Copy scripts/migrate-checkin.env.example to
//      scripts/migrate-checkin.env.local and fill it in. That file is
//      gitignored - never commit it.
//   3. node scripts/migrate-checkin-dev-to-prod.js            (dry run)
//      node scripts/migrate-checkin-dev-to-prod.js --apply    (writes)

const fs = require("fs");
const path = require("path");
const readline = require("readline");
const { createClient } = require("@supabase/supabase-js");

function loadEnvFile(file) {
  if (!fs.existsSync(file)) return {};
  const out = {};
  for (const line of fs.readFileSync(file, "utf-8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const idx = trimmed.indexOf("=");
    if (idx === -1) continue;
    out[trimmed.slice(0, idx).trim()] = trimmed.slice(idx + 1).trim();
  }
  return out;
}

const env = {
  ...loadEnvFile(path.join(__dirname, "migrate-checkin.env.local")),
  ...process.env,
};

const {
  SOURCE_SUPABASE_URL,
  SOURCE_SERVICE_ROLE_KEY,
  TARGET_SUPABASE_URL,
  TARGET_SERVICE_ROLE_KEY,
} = env;
const SOURCE_ATTENDEES_TABLE = env.SOURCE_ATTENDEES_TABLE || "attendees";
const SOURCE_SCAN_LOG_TABLE = env.SOURCE_SCAN_LOG_TABLE || "scan_log";
const TARGET_ATTENDEES_TABLE = "checkin_attendees";
const TARGET_SCAN_LOG_TABLE = "checkin_scan_log";

const args = new Set(process.argv.slice(2));
const APPLY = args.has("--apply");
const ALLOW_NONEMPTY = args.has("--allow-nonempty");
const ASSUME_YES = args.has("--yes");

const missing = Object.entries({
  SOURCE_SUPABASE_URL,
  SOURCE_SERVICE_ROLE_KEY,
  TARGET_SUPABASE_URL,
  TARGET_SERVICE_ROLE_KEY,
})
  .filter(([, v]) => !v)
  .map(([k]) => k);
if (missing.length > 0) {
  console.error(`Missing config: ${missing.join(", ")}`);
  console.error("Set these in scripts/migrate-checkin.env.local (see migrate-checkin.env.example).");
  process.exit(1);
}

const projectRef = (url) => new URL(url).hostname.split(".")[0];
const source = createClient(SOURCE_SUPABASE_URL, SOURCE_SERVICE_ROLE_KEY, {
  auth: { persistSession: false },
});
const target = createClient(TARGET_SUPABASE_URL, TARGET_SERVICE_ROLE_KEY, {
  auth: { persistSession: false },
});

const ATTENDEE_COLUMNS = [
  "id",
  "ticket_number",
  "confirmation",
  "name",
  "email",
  "phone",
  "organization",
  "designation",
  "ticket_type",
  "source",
  "is_team",
  "team_role",
  "checked_in_at",
  "checked_in_by",
  "bag_given_at",
  "bag_given_by",
  "pass_emailed_at",
  "created_at",
  "updated_at",
];
const SCAN_LOG_COLUMNS = ["created_at", "ticket_number", "attendee_id", "station", "result", "staff"];

async function fetchAll(client, table, orderBy) {
  const PAGE = 1000;
  const out = [];
  for (let from = 0; ; from += PAGE) {
    const { data, error } = await client
      .from(table)
      .select("*")
      .order(orderBy)
      .range(from, from + PAGE - 1);
    if (error) throw new Error(`Reading ${table} failed: ${error.message}`);
    out.push(...(data ?? []));
    if (!data || data.length < PAGE) break;
  }
  return out;
}

// Not a HEAD request on purpose: against a table that doesn't exist, HEAD
// comes back with no error body (error stays null and count is null), which
// reads as "0 rows, all fine". A normal select reports the real error. And a
// null count is treated as a failure, never as zero.
async function count(client, table, filter) {
  let q = client.from(table).select("*", { count: "exact" });
  if (filter) q = filter(q);
  const { count: c, error } = await q.limit(1);
  if (error) throw new Error(`Counting ${table} failed: ${error.message}`);
  if (c === null || c === undefined) {
    throw new Error(`Counting ${table} returned no count - does the table exist?`);
  }
  return c;
}

function pick(row, columns) {
  const out = {};
  for (const c of columns) out[c] = row[c] === undefined ? null : row[c];
  return out;
}

async function summarise(client, attendeesTable, scanLogTable) {
  return {
    attendees: await count(client, attendeesTable),
    checkedIn: await count(client, attendeesTable, (q) => q.not("checked_in_at", "is", null)),
    bagsGiven: await count(client, attendeesTable, (q) => q.not("bag_given_at", "is", null)),
    team: await count(client, attendeesTable, (q) => q.eq("is_team", true)),
    walkIns: await count(client, attendeesTable, (q) => q.eq("source", "walkin")),
    passEmailed: await count(client, attendeesTable, (q) => q.not("pass_emailed_at", "is", null)),
    scanLog: await count(client, scanLogTable),
  };
}

function ask(question) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  return new Promise((resolve) =>
    rl.question(question, (answer) => {
      rl.close();
      resolve(answer.trim());
    }),
  );
}

async function main() {
  const targetRef = projectRef(TARGET_SUPABASE_URL);
  console.log(`SOURCE: ${projectRef(SOURCE_SUPABASE_URL)}  (${SOURCE_ATTENDEES_TABLE}, ${SOURCE_SCAN_LOG_TABLE})`);
  console.log(`TARGET: ${targetRef}  (${TARGET_ATTENDEES_TABLE}, ${TARGET_SCAN_LOG_TABLE})`);
  console.log(APPLY ? "Mode:   APPLY (will write)\n" : "Mode:   dry run (nothing will be written)\n");

  // The target tables must exist (migration 0016) - fail clearly if not.
  for (const table of [TARGET_ATTENDEES_TABLE, TARGET_SCAN_LOG_TABLE]) {
    const { error } = await target.from(table).select("*").limit(1);
    if (error) {
      throw new Error(
        `Target table ${table} isn't usable (${error.message}). ` +
          `Run supabase/migrations/0016_event_checkin.sql on the target project first.`,
      );
    }
  }

  const [attendees, scanLog] = await Promise.all([
    fetchAll(source, SOURCE_ATTENDEES_TABLE, "created_at"),
    fetchAll(source, SOURCE_SCAN_LOG_TABLE, "id"),
  ]);
  const srcTeam = attendees.filter((a) => a.is_team).length;
  console.log(
    `Read from source: ${attendees.length} attendees (${srcTeam} team), ${scanLog.length} scan-log rows`,
  );

  const existing = await count(target, TARGET_ATTENDEES_TABLE);
  const existingLog = await count(target, TARGET_SCAN_LOG_TABLE);
  console.log(`Target currently holds: ${existing} attendees, ${existingLog} scan-log rows\n`);
  if ((existing > 0 || existingLog > 0) && !ALLOW_NONEMPTY) {
    throw new Error(
      "The target tables aren't empty. Refusing to copy on top (it would duplicate the scan log). " +
        "Truncate checkin_scan_log and checkin_attendees in the SQL Editor to start over, " +
        "or pass --allow-nonempty if you really mean it.",
    );
  }

  if (!APPLY) {
    console.log("Dry run only. Looks good? Run again with --apply to copy it.");
    return;
  }

  if (!ASSUME_YES) {
    const typed = await ask(`Type the target project ref (${targetRef}) to confirm writing there: `);
    if (typed !== targetRef) {
      console.log("Doesn't match - nothing written.");
      return;
    }
  }

  // Attendees first (the scan log references them), ids preserved.
  const CHUNK = 200;
  const attendeeRows = attendees.map((a) => pick(a, ATTENDEE_COLUMNS));
  for (let i = 0; i < attendeeRows.length; i += CHUNK) {
    const { error } = await target.from(TARGET_ATTENDEES_TABLE).insert(attendeeRows.slice(i, i + CHUNK));
    if (error) throw new Error(`Writing attendees failed at row ${i}: ${error.message}`);
  }
  console.log(`Copied ${attendeeRows.length} attendees`);

  const logRows = scanLog.map((s) => pick(s, SCAN_LOG_COLUMNS));
  for (let i = 0; i < logRows.length; i += CHUNK) {
    const { error } = await target.from(TARGET_SCAN_LOG_TABLE).insert(logRows.slice(i, i + CHUNK));
    if (error) throw new Error(`Writing scan log failed at row ${i}: ${error.message}`);
  }
  console.log(`Copied ${logRows.length} scan-log rows\n`);

  // Verify: the same numbers must come back out of the target.
  const [before, after] = await Promise.all([
    summarise(source, SOURCE_ATTENDEES_TABLE, SOURCE_SCAN_LOG_TABLE),
    summarise(target, TARGET_ATTENDEES_TABLE, TARGET_SCAN_LOG_TABLE),
  ]);
  let allMatch = true;
  console.log("Check".padEnd(14), "source".padStart(8), "target".padStart(8));
  for (const key of Object.keys(before)) {
    const ok = before[key] === after[key];
    if (!ok) allMatch = false;
    console.log(key.padEnd(14), String(before[key]).padStart(8), String(after[key]).padStart(8), ok ? "  ok" : "  MISMATCH");
  }
  console.log(allMatch ? "\nAll counts match." : "\nCOUNTS DO NOT MATCH - investigate before relying on the target.");
  if (!allMatch) process.exitCode = 1;
}

main().catch((e) => {
  console.error(`\nFAILED: ${e.message}`);
  // exitCode, not process.exit(): exiting while sockets are still closing
  // trips a harmless-but-ugly assertion on Windows.
  process.exitCode = 1;
});
